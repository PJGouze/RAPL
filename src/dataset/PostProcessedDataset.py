class ProcessedDiskDataset(Dataset):
    def __init__(self,
                 processed_dir,
                 split,
                 raw_dataset=None,
                 labeled_topic_relation_path=None,  # Path to labeled relations from gpt4o-mini
                 retrieval_list=None,               # loaded pickle from {split}_retrieval.pkl
                 text_labels=None,                  # loaded pickle from dir of annotated labels from gpt4o
                 metadata_list=None,
                 cache_signature=None,
                 force_reprocess=False,
                 sample_limit=None):
        
        """
        Construct a processed graph dataset enriched with reasoning-path and
        relation-level supervision for retriever training.

        This dataset serves as the final preprocessing stage before training the
        graph retriever. It combines information from the original knowledge graph,
        retrieved candidate reasoning paths, manually or LLM-annotated reasoning
        paths, metadata describing the line graph, and relation predictions
        generated by a large language model.

        For each sample, the class performs the following operations:

        1. Matches retrieved reasoning paths with the annotated (ground-truth)
        reasoning paths.
        2. Converts the matched reasoning paths into graph triplets and builds a
        ``path_label`` tensor describing the order of graph nodes along each
        reasoning path.
        3. Parses the LLM-predicted relevant relations and converts them into
        node-level supervision by creating a ``topic_labels`` tensor.
        4. Stores the processed graph objects as ``.pt`` files on disk for efficient
        loading during model training.

        If the processed dataset already exists, no preprocessing is performed and
        the graphs are loaded directly from disk.

        Parameters
        ----------
        processed_dir : str
            Root directory where the processed dataset will be stored or loaded.

        split : {"train", "val", "test"}
            Dataset split to process.

        raw_dataset : torch_geometric.data.Dataset, optional
            Original graph dataset. Required only during the first preprocessing
            pass when processed files do not yet exist.

        labeled_topic_relation_path : str, optional
            Path to the pickle file containing the LLM outputs for each question.
            Each sample must contain the predicted relevant relations in the
            ``response_text`` field.

        retrieval_list : list of dict, optional
            Retrieved candidate reasoning paths for every sample. Each dictionary
            typically contains translated paths, reasoning paths, entity mappings,
            and relation mappings.

        text_labels : list of list of tuple, optional
            Ground-truth reasoning paths for every sample. Each reasoning path is
            represented as a tuple of relation names.

        metadata_list : list of list of dict, optional
            Metadata describing every node of the line graph. Each node is
            associated with its corresponding graph triple:

                {
                    "h_id": int,
                    "relation_id": int,
                    "t_id": int
                }

            The ordering must match the node ordering of the processed graph.

        Attributes
        ----------
        split : str
            Dataset split.

        split_dir : str
            Directory containing the processed graph objects.

        raw_dataset : Dataset
            Original graph dataset used during preprocessing.

        retrieval_list : list
            Candidate reasoning paths.

        text_labels : list
            Ground-truth reasoning paths.

        labeled_topic_relation : list
            Parsed LLM predictions loaded from
            ``labeled_topic_relation_path``.

        metadata_list : list
            Metadata describing every line-graph node. Correction : It is actually the "encoding" of the graph :
            {
            "h_id":20,
            "relation_id":4,
            "t_id":35
          }
          This permit to use more easily the NetworkX graph and form the lineGraph

        min_len_indices_list : list
            Stores indices of candidate paths whose length is smaller than or equal
            to the minimum ground-truth path length. These indices are retained for
            later analysis.

        Notes
        -----
        The generated graph objects contain additional supervision compared to the
        original dataset, including:

        - ``path_label``:
        Encodes the reasoning-path supervision by indicating the position of
        every graph node within each matched reasoning path.

        - ``topic_labels``:
        Binary labels identifying graph nodes whose relations were predicted as
        relevant by the LLM or belong to the annotated reasoning paths.

        These labels are subsequently used to train the graph retriever.

        """

        if split not in ['train', 'val', 'test']:
            raise ValueError(f"Unsupported split {split!r}; expected train, val, or test.")

        if sample_limit is not None and sample_limit <= 0:
            raise ValueError(
                f"sample_limit must be strictly positive, got {sample_limit!r}."
            )

        self.sample_limit = sample_limit
        #creating the directory
        self.split = split
        self.split_dir = os.path.join(processed_dir, split)
        os.makedirs(self.split_dir, exist_ok=True)

        self.raw_dataset = None
        self.retrieval_list = None
        self.text_labels = None
        self.labeled_topic_relation = None
        self.metadata_list = None  # We'll store a "global" metadata_list reference

        self.min_len_indices_list =[]

        self.cache_manifest_path = os.path.join(
            self.split_dir, "postprocess_manifest.json"
        )
        expected_samples = len(raw_dataset) if raw_dataset is not None else None
        cache_state, cache_reason = self._cache_state(
            expected_samples=expected_samples,
            expected_signature=cache_signature,
        )
        if cache_state == "valid" and not force_reprocess:
            print(f"Reusing complete valid cache for split={split!r}: {cache_reason}")
            super().__init__(root=None)
            return
        if cache_state != "empty" and not force_reprocess:
            print(
                f"WARNING: {cache_state} cache for split={split!r}: {cache_reason}"
            )
            raise RuntimeError(
                f"Cannot reuse {cache_state} cache for split={split!r}: "
                f"{cache_reason}. Pass force_reprocess=True (CLI: --force-reprocess) "
                "to explicitly regenerate it."
            )
        if force_reprocess:
            print(
                f"Explicit forced regeneration for split={split!r}; "
                f"previous cache state={cache_state!r}."
            )

        context = f"split={split!r}"
        if raw_dataset is None:
            raise ValueError(f"raw_dataset is required ({context}).")
        if labeled_topic_relation_path is None:
            raise ValueError(f"labeled_topic_relation_path is required ({context}).")
        if retrieval_list is None:
            raise ValueError(f"retrieval_list is None ({context}).")
        if text_labels is None:
            raise ValueError(f"text_labels is None ({context}).")
        if metadata_list is None:
            raise ValueError(f"metadata_list is None ({context}).")
        if not text_labels and retrieval_list:
            raise ValueError(f"text_labels is empty ({context}).")
        if len(text_labels) != len(retrieval_list):
            raise ValueError(
                f"Label/retrieval length mismatch ({context}): "
                f"labels={len(text_labels)}, retrieval={len(retrieval_list)}."
            )
        if len(metadata_list) != len(retrieval_list):
            raise ValueError(
                f"Metadata/retrieval length mismatch ({context}): "
                f"metadata={len(metadata_list)}, retrieval={len(retrieval_list)}."
            )
        if len(raw_dataset) != len(retrieval_list):
            raise ValueError(
                f"Graph/retrieval length mismatch ({context}): "
                f"graphs={len(raw_dataset)}, retrieval={len(retrieval_list)}."
            )
        for sample_index, paths in enumerate(text_labels):
            if not paths:
                sample = retrieval_list[sample_index]
                sample_id = sample.get("id", sample_index)
                raise ValueError(
                    f"Empty text label ({context}, sample_index={sample_index}, "
                    f"sample_id={sample_id!r})."
                )

        # Store references for processing
        self.raw_dataset = raw_dataset
        self.retrieval_list = retrieval_list
        self.text_labels = text_labels
        self.metadata_list = metadata_list

        all_labeled_topic_relations = self._load_labeled_topic_relation(
            labeled_topic_relation_path
        )

        if self.sample_limit is not None:
            if len(all_labeled_topic_relations) < self.sample_limit:
                raise ValueError(
                    f"Not enough topic-relation records for split={split!r}: "
                    f"available={len(all_labeled_topic_relations)}, "
                    f"requested={self.sample_limit}."
                )

            all_labeled_topic_relations = all_labeled_topic_relations[
                :self.sample_limit
            ]

        self.labeled_topic_relation = all_labeled_topic_relations

        if len(self.labeled_topic_relation) != len(retrieval_list):
            raise ValueError(
                f"Topic-relation/retrieval length mismatch ({context}): "
                f"topic_relations={len(self.labeled_topic_relation)}, "
                f"retrieval={len(retrieval_list)}."
            )
        for sample_index, (retrieval_sample, topic_relation_sample) in enumerate(
            zip(retrieval_list, self.labeled_topic_relation)
        ):
            retrieval_question = retrieval_sample.get("question")
            topic_relation_question = topic_relation_sample.get("question")
            if (
                retrieval_question is not None
                and topic_relation_question is not None
                and retrieval_question != topic_relation_question
            ):
                sample_id = retrieval_sample.get("id", sample_index)
                raise ValueError(
                    f"Question alignment mismatch for split={split!r}, "
                    f"sample_index={sample_index}, sample_id={sample_id!r}: "
                    f"retrieval_question={retrieval_question!r}, "
                    f"topic_relation_question={topic_relation_question!r}."
                )
        self._regenerate_transactionally(cache_signature)

        super().__init__(root=None)

    def _get_metadata_from_data(self, data_obj):

        return [
            {
                "h_id": h,
                "relation_id": r,
                "t_id": t
            }
            for h,r,t in zip(
                data_obj.h_id_list,
                data_obj.r_id_list,
                data_obj.t_id_list
            )
        ]

    def _cache_state(self, expected_samples, expected_signature):
        indexed_files = {}
        for file_name in os.listdir(self.split_dir):
            match = re.fullmatch(r"data_(\d+)\.pt", file_name)
            if match:
                indexed_files[int(match.group(1))] = file_name
        if not indexed_files:
            return "empty", "no cached graph files"
        if expected_samples is not None:
            expected_indices = set(range(expected_samples))
            if set(indexed_files) != expected_indices:
                return (
                    "incomplete",
                    f"graph indices={sorted(indexed_files)}, "
                    f"expected={sorted(expected_indices)}",
                )
        if not os.path.isfile(self.cache_manifest_path):
            return "unverifiable", "postprocess manifest is missing"
        try:
            with open(self.cache_manifest_path, encoding="utf-8") as manifest_file:
                manifest = json.load(manifest_file)
        except (OSError, ValueError) as error:
            return "unverifiable", f"postprocess manifest cannot be read: {error}"
        manifest_sample_count = manifest.get("sample_count")
        if expected_samples is None:
            expected_samples = manifest_sample_count
        if not isinstance(expected_samples, int) or expected_samples < 0:
            return "unverifiable", "expected graph count is unavailable"
        expected_indices = set(range(expected_samples))
        if set(indexed_files) != expected_indices:
            return (
                "incomplete",
                f"graph indices={sorted(indexed_files)}, expected={sorted(expected_indices)}",
            )
        if (
            manifest.get("schema_version") != 1
            or manifest.get("split") != self.split
            or manifest.get("sample_count") != expected_samples
            or not manifest.get("input_signature")
            or (
                expected_signature is not None
                and manifest.get("input_signature") != expected_signature
            )
        ):
            return "stale", "postprocess manifest does not match the current inputs"
        for sample_index in range(expected_samples):
            try:
                graph = torch.load(
                    os.path.join(self.split_dir, indexed_files[sample_index]),
                    map_location="cpu",
                    weights_only=False,
                )
            except Exception as error:
                return "unverifiable", f"data_{sample_index}.pt cannot be loaded: {error}"
            missing_attributes = [
                name
                for name in ("path_label", "topic_labels", "topic_candidates")
                if not hasattr(graph, name)
            ]
            if missing_attributes:
                return (
                    "stale",
                    f"data_{sample_index}.pt lacks {missing_attributes}",
                )
            if not torch.any(graph.path_label == 0):
                return "stale", f"data_{sample_index}.pt has no valid supervised path"
        return "valid", f"{expected_samples} contiguous graphs and matching manifest"

    def _write_cache_manifest(self, cache_signature, output_dir):
        manifest = {
            "schema_version": 1,
            "split": self.split,
            "sample_count": len(self.raw_dataset),
            "input_signature": cache_signature,
            "complete_dataset": self.sample_limit is None,
            "sample_limit": self.sample_limit,
        }
        manifest_path = os.path.join(output_dir, "postprocess_manifest.json")
        temporary_path = f"{manifest_path}.tmp"
        with open(temporary_path, "w", encoding="utf-8") as manifest_file:
            json.dump(manifest, manifest_file, sort_keys=True)
            manifest_file.write("\n")
        os.replace(temporary_path, manifest_path)

    def _validate_generated_cache(self, output_dir):
        expected_indices = set(range(len(self.raw_dataset)))
        output_indices = {
            int(match.group(1))
            for file_name in os.listdir(output_dir)
            if (match := re.fullmatch(r"data_(\d+)\.pt", file_name))
        }
        if output_indices != expected_indices:
            raise RuntimeError(
                f"Staged cache is incomplete for split={self.split!r}: "
                f"graph indices={sorted(output_indices)}, "
                f"expected={sorted(expected_indices)}."
            )
        for sample_index in range(len(self.raw_dataset)):
            graph_path = os.path.join(output_dir, f"data_{sample_index}.pt")
            graph = torch.load(graph_path, map_location="cpu", weights_only=False)
            missing_attributes = [
                name
                for name in ("path_label", "topic_labels", "topic_candidates")
                if not hasattr(graph, name)
            ]
            if missing_attributes:
                raise RuntimeError(
                    f"Staged graph validation failed for split={self.split!r}, "
                    f"sample_index={sample_index}: missing {missing_attributes}."
                )
            if not torch.any(graph.path_label == 0):
                raise RuntimeError(
                    f"Staged graph validation failed for split={self.split!r}, "
                    f"sample_index={sample_index}: no supervised reasoning path."
                )

    def _regenerate_transactionally(self, cache_signature):
        processed_dir = os.path.dirname(self.split_dir)
        staging_dir = tempfile.mkdtemp(
            prefix=f".{self.split}.staging-", dir=processed_dir
        )
        previous_dir = f"{self.split_dir}.previous-{uuid.uuid4().hex}"
        try:
            replaced_names = {
                "postprocess_manifest.json",
                "metadata_list.pkl",
                "min_len_indices_list.pkl",
            }
            for entry_name in os.listdir(self.split_dir):
                if (
                    entry_name in replaced_names
                    or re.fullmatch(r"data_\d+\.pt", entry_name)
                ):
                    continue
                source_path = os.path.join(self.split_dir, entry_name)
                destination_path = os.path.join(staging_dir, entry_name)
                if os.path.isdir(source_path):
                    shutil.copytree(source_path, destination_path)
                else:
                    shutil.copy2(source_path, destination_path)
            self._process_all(staging_dir)
            self._validate_generated_cache(staging_dir)
            self._write_cache_manifest(cache_signature, staging_dir)

            os.replace(self.split_dir, previous_dir)
            try:
                os.replace(staging_dir, self.split_dir)
            except Exception:
                os.replace(previous_dir, self.split_dir)
                raise
            shutil.rmtree(previous_dir)
        except Exception:
            if os.path.isdir(staging_dir):
                shutil.rmtree(staging_dir)
            raise

    def _load_labeled_topic_relation(self, path):
        with open(path, 'rb') as f:
            return pickle.load(f)


    def _process_all(self, output_dir):
        """
        Iterate over raw_dataset, attach metadata_list[sample_idx],
        rebuild path_label, create topic_labels, etc., then save to disk.
        """
        # print('#### Inside process_all ####')
        # print("raw_dataset:", self.raw_dataset)
        # print("raw_dataset type:", type(self.raw_dataset))
        # print("raw_dataset len:", len(self.raw_dataset))
        for sample_idx, data_obj in enumerate(tqdm(self.raw_dataset, desc="Post Processing dataset")):
            # (A) Attach the node-level metadata for line graph nodes
            #     e.g. a list of dict, each: {"h_id":..., "relation_id":..., "t_id":...}
            #     so we can label them.

            # (B) Add new attributes (path_label, topic_labels, etc.)
            out_path = os.path.join(output_dir, f'data_{sample_idx}.pt')

            try:
                data_obj = self._compute_and_add_new_attr(data_obj, sample_idx)
                temporary_path = f"{out_path}.tmp"
                torch.save(data_obj, temporary_path)
                os.replace(temporary_path, out_path)
            except Exception as error:
                raise RuntimeError(
                    f"Post-processing failed for split={self.split!r}, "
                    f"sample_index={sample_idx}: {error}"
                ) from error

        # save the min_len_indices_list and meta_list
        with open(os.path.join(output_dir, f'min_len_indices_list.pkl'), 'wb') as f:
            pickle.dump(self.min_len_indices_list, f,protocol=pickle.HIGHEST_PROTOCOL)
        with open(os.path.join(output_dir, f'metadata_list.pkl'), 'wb') as f:
            pickle.dump(self.metadata_list, f,protocol=pickle.HIGHEST_PROTOCOL)

    def _compute_and_add_new_attr(self, data_obj, sample_idx):
        # if sample_idx == 1:
        #     # print('### inside compute and add new attribute ###')

        data_obj = self._rebuild_path_label(data_obj, sample_idx)

        data_obj = self._update_topic_labels(data_obj, sample_idx)

        # Preserve candidate mask from KGDataset
        if not hasattr(data_obj, "topic_candidates"):
            raise AttributeError(
                "topic_candidates missing from raw KGDataset"
            )

        return data_obj

    def _rebuild_path_label(self, data_obj, sample_idx):
        # if sample_idx == 1:
        #     print('### inside rebuild path label ###')
        ground_truth_tuples = self.text_labels[sample_idx]
        reasoning_paths     = self.retrieval_list[sample_idx]["reasoning_paths"]
        translated_paths    = self.retrieval_list[sample_idx]["translated_paths"]
        id2entities         = self.retrieval_list[sample_idx]["id2entities"]
        id2relations        = self.retrieval_list[sample_idx]["id2relations"]
        # max key from id2entities
        max_entity_id = max(id2entities.keys())
        max_str = id2entities[max_entity_id]
        

        # 1) Match
        matched_indices, min_len_indices = self._match_candidate_paths(
            ground_truth_tuples,
            reasoning_paths
        )
        if not matched_indices:
            sample_id = self.retrieval_list[sample_idx].get("id", sample_idx)
            raise ValueError(
                f"No annotated relation path matches a retrieved path for "
                f"split={self.split!r}, sample_index={sample_idx}, "
                f"sample_id={sample_id!r}; annotations={ground_truth_tuples!r}."
            )
        self.min_len_indices_list.append(min_len_indices)

        # 2) Convert matched paths to triplets
        matched_paths_triplets = []
        for m_idx in matched_indices:
            if m_idx < len(translated_paths):
                path_strs = [translated_paths[m_idx]]
                triple_lists = self._paths_to_triplets(id2entities, id2relations, path_strs,maxEntStr = max_str)
                for triple_seq in triple_lists:
                    matched_paths_triplets.append(triple_seq)

        # 3) Rebuild path_label
        max_paths = 10
        num_nodes = data_obj.num_nodes
        path_label = -1 * torch.ones(num_nodes, max_paths, dtype=torch.long)

        # We stored the node-level metadata already in each sample
        # meta_dict = self._get_metadata_from_data(data_obj)
        meta_dict = self.metadata_list[sample_idx]
        if len(meta_dict) != num_nodes:
            raise ValueError(
                f"Metadata/node mismatch for split={self.split!r}, "
                f"sample_index={sample_idx}: metadata_nodes={len(meta_dict)}, "
                f"graph_nodes={num_nodes}."
            )

        for path_idx, triple_seq in enumerate(matched_paths_triplets[:max_paths]):
            for step_i, (h, r, t) in enumerate(triple_seq):
                for node_idx in range(num_nodes):
                    if (meta_dict[node_idx]['h_id'] == h and
                        meta_dict[node_idx]['relation_id'] == r and
                        meta_dict[node_idx]['t_id'] == t):
                        path_label[node_idx, path_idx] = step_i
                        break

        data_obj.path_label = path_label
        return data_obj

